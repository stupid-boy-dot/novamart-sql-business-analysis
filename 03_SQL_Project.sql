-- PROJECT 3: CUSTOMER ANALYTICS
-- TASK 2: REVENUE PER CUSTOMER BY AGE GROUP
-- Business Question:
-- Which age group generates the most revenue
-- per customer?
-- =====================================================

SELECT
    CASE
        WHEN c.age BETWEEN 18 AND 25 THEN '18-25'
        WHEN c.age BETWEEN 26 AND 35 THEN '26-35'
        WHEN c.age BETWEEN 36 AND 45 THEN '36-45'
        WHEN c.age BETWEEN 46 AND 55 THEN '46-55'
        ELSE '56+'
    END AS age_group,

    -- Total revenue generated by the age group
    SUM(
        oi.quantity
        * oi.unit_price
        * (1 - oi.discount_percent / 100)
    ) AS total_revenue,

    -- Number of unique customers
    COUNT(DISTINCT c.customer_id) AS customer_count,

    -- Average revenue generated per customer
    ROUND(
        SUM(
            oi.quantity
            * oi.unit_price
            * (1 - oi.discount_percent / 100)
        )
        / COUNT(DISTINCT c.customer_id),
        2
    ) AS revenue_per_customer

FROM customers AS c

JOIN orders AS o
    ON c.customer_id = o.customer_id

JOIN order_items AS oi
    ON o.order_id = oi.order_id

GROUP BY
    age_group

ORDER BY
    revenue_per_customer DESC;
    
    
