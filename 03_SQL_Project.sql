-- TASK 14: HIGH-VALUE CUSTOMER IDENTIFICATION
-- Business Question:
-- Which customers are both high-value and frequent buyers?
-- =====================================================

SELECT
    c.customer_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,

    -- Total revenue generated by the customer
    SUM(
        oi.quantity
        * oi.unit_price
        * (1 - oi.discount_percent / 100)
    ) AS lifetime_revenue,

    -- Number of unique orders
    COUNT(DISTINCT o.order_id) AS order_count

FROM customers AS c

JOIN orders AS o
    ON c.customer_id = o.customer_id

JOIN order_items AS oi
    ON o.order_id = oi.order_id

GROUP BY
    c.customer_id,
    c.first_name,
    c.last_name

-- High-value + frequent-purchase criteria
HAVING
    SUM(
        oi.quantity
        * oi.unit_price
        * (1 - oi.discount_percent / 100)
    ) > 1000000
    AND COUNT(DISTINCT o.order_id) >= 5

ORDER BY lifetime_revenue DESC;


-- =====================================================
-- PROJECT 3: CUSTOMER ANALYTICS
-- TASK 15: CUSTOMER SEGMENTATION
-- =====================================================

SELECT
    CASE
        WHEN lifetime_revenue >= 1000000
             AND order_count >= 8
            THEN 'VIP'

        WHEN lifetime_revenue >= 500000
             AND order_count >= 4
            THEN 'Loyal'

        WHEN lifetime_revenue >= 200000
             AND order_count >= 2
            THEN 'Regular'

        ELSE 'One-Time / Low Value'
    END AS customer_segment,

    COUNT(*) AS customer_count

FROM (
    -- Calculate revenue and order frequency per customer
    SELECT
        c.customer_id,

        SUM(
            oi.quantity
            * oi.unit_price
            * (1 - oi.discount_percent / 100)
        ) AS lifetime_revenue,

        COUNT(DISTINCT o.order_id) AS order_count

    FROM customers AS c

    JOIN orders AS o
        ON c.customer_id = o.customer_id

    JOIN order_items AS oi
        ON o.order_id = oi.order_id

    GROUP BY c.customer_id
) AS customer_metrics

GROUP BY
    CASE
        WHEN lifetime_revenue >= 1000000
             AND order_count >= 8
            THEN 'VIP'

        WHEN lifetime_revenue >= 500000
             AND order_count >= 4
            THEN 'Loyal'

        WHEN lifetime_revenue >= 200000
             AND order_count >= 2
            THEN 'Regular'

        ELSE 'One-Time / Low Value'
    END

ORDER BY customer_count DESC;