-- TASK 13: CUSTOMER RETENTION-STYLE ANALYSIS
-- Business Question:
-- How many customers purchased across multiple years?
-- =====================================================

SELECT
    purchase_year_count,

    -- Number of customers who purchased in this many years
    COUNT(*) AS customer_count

FROM (
    -- Count the number of different years each customer
    -- made at least one purchase
    SELECT
        customer_id,
        COUNT(DISTINCT YEAR(order_date)) AS purchase_year_count
    FROM orders
    GROUP BY customer_id
) AS customer_years

GROUP BY purchase_year_count
ORDER BY purchase_year_count;


